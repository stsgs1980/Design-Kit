/**
 * Категория паттерна: по ней строится первый фильтр на `/patterns`.
 *
 * `recipes` — не приём из музея, а собранная композиция кита с порядком шагов.
 * Категория отдельная, чтобы наборы не смешивались с приёмами в списке.
 */
export type PatternCategory =
  "typography" | "surfaces" | "backgrounds" | "interactions" | "visual" | "conceptual" | "recipes";

/** Откуда приём: из музея паттернов или это собственный концепт кита. */
export type PatternOrigin = "museum" | "concept";

/** Вердикт музея: приём на подъёме, устоялся или выходит из моды. */
export type PatternVerdict = "stable" | "rising" | "fading";

/** Часть композиции: какой компонент кита и какую роль он играет. */
export type PatternPart = {
  /** id записи кита: ссылка ведёт на `/kit/<id>`. */
  kit: string;
  /** Роль в паттерне: «подложка», «стекло», «акцент». */
  role: string;
};

/** Запись справочника паттернов: приём уровня страницы, а не атом. */
export type PatternEntry = {
  /** Стабильный id: совпадает с папкой демо `components/patterns/<id>/`. */
  id: string;
  /** Русское название. */
  name: string;
  /** Английское имя приёма: по нему паттерн ищут в музее. */
  latin: string;
  /** Одна строка: что это за приём. */
  summary: string;
  category: PatternCategory;
  verdict: PatternVerdict;
  /** Год появления. */
  from: number;
  /** Год, до которого приём актуален: если не указан — актуален сейчас. */
  to?: number;
  /** Когда брать: одна-две фразы без общих слов. */
  when: string;
  /** Из каких компонентов кита собирается: только реальные id манифеста. */
  composition: PatternPart[];
  /** Правила: что делает паттерн собой, а не пародией. */
  rules: string[];
  /** Грабли: на чём приём ломается. */
  pitfalls: string[];
  /** Цена словами: что уезжает в браузер. */
  cost: string;
  /**
   * Откуда приём. `museum` — есть ссылка на оригинал, `concept` — собственный
   * разбор кита; тогда ссылки нет, а референс описан в `notes`.
   */
  origin?: PatternOrigin;
  /** Ссылка на оригинал: обязательна для приёма из музея. */
  source?: string;
  /** Свободная строка подвала: чем приём отличается от оригинала. */
  notes?: string;
  /** Где приём уже применён в нашей работе. */
  where: string[];
};
