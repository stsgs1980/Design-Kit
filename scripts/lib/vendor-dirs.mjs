/**
 * Вендорные каталоги: чужой код, который лежит в репозитории, но не является
 * нашим.
 *
 * Зачем отдельный модуль: у нас пять независимых проверок (eslint, prettier,
 * markdownlint, tsc, анти-монолит), и каждая собирает свой список файлов.
 * Скилы агентов приезжают как есть — со своими emoji, `console.log`, файлами на
 * 700 строк и без выравнивания markdown. Если исключать их по одному месту,
 * завтрашняя правка конфига снова уронит гейты на чужом коде.
 *
 * Правило: вендорный каталог исключается везде, а `npm run verify:vendor`
 * сверяет, что ни одна из проверок про него не забыла.
 *
 * Сейчас каталогов в репозитории нет: скилы агентов приходят из глобальной
 * установки (плагин opencode, каталог `~/.agents`), а не из проекта. Список
 * ниже — не факт, а правило: если вендорный каталог вернут в репозиторий,
 * объявить его здесь и исключить сразу во всех пяти проверках. Гейт ловит
 * оба случая: заявленный каталог должен быть исключен, а лежащий на диске
 * каталог — заявлен.
 */

/** Каталоги вендорного кода, пути от корня репозитория. */
export const VENDOR_DIRS = [];

/** Шаблоны для конфигов, которые думают глобами (eslint, prettier). */
export const VENDOR_GLOBS = [".claude/**"];

/**
 * Базовые каталоги из шаблонов: `.claude/**` -> `.claude`.
 * @returns {string[]} корни, которые должны стоять в списках исключений
 */
export function vendorRoots() {
  return VENDOR_GLOBS.map((glob) => glob.replace(/\/\*\*$/, ""));
}

/**
 * Лежит ли файл в вендорном каталоге.
 * @param {string} file - путь от корня репозитория, с прямыми слэшами
 * @returns {boolean} true для файлов и каталогов внутри VENDOR_DIRS
 */
export function isVendored(file) {
  const normalized = file.replace(/\\/g, "/").replace(/^\.\//, "");

  return VENDOR_DIRS.some((dir) => normalized === dir || normalized.startsWith(`${dir}/`));
}
